/**
 * Copy LitNode's browser client into src/litnode/mesh/: the arcade's queue and placement client (cabinet/client.js)
 * and the protocol modules it and the mesh discovery need, byte for byte, so the game queues, verifies a placement and
 * signs exactly as the arcade does. LitNode is Apache-2.0. The manifest pins every copy by sha256 and records the
 * LitNode version it came from.
 *
 *   node scripts/vendor-litnode.mjs          copy from ../LITNODE/litnode (or LITNODE_DIR)
 *   node scripts/vendor-litnode.mjs --check  exit 1 when a copy differs from its manifest entry
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src', 'litnode', 'mesh');
const PROTOCOL = ['canonical.js', 'keys.js', 'keccak.js', 'staking.js', 'abi.js', 'directory.js', 'placement.js', 'pairing.js', 'snapshot.js', 'challenge.js', 'log.js'];
const FILES = ['client.js', ...PROTOCOL.map((f) => `protocol/${f}`)];
const sha = (b) => createHash('sha256').update(b.toString('utf8').replace(/\r\n/g, '\n')).digest('hex');

if (process.argv.includes('--check')) {
  const m = JSON.parse(readFileSync(join(out, 'MANIFEST.json'), 'utf8'));
  const bad = FILES.filter((f) => !existsSync(join(out, f)) || m.files[f] !== sha(readFileSync(join(out, f))));
  if (bad.length) { console.error(`edited or missing: ${bad.join(', ')} (run node scripts/vendor-litnode.mjs)`); process.exit(1); }
  console.log(`src/litnode/mesh matches LitNode ${m.litnode} (${FILES.length} files)`);
} else {
  const src = resolve(process.env.LITNODE_DIR ?? join(root, '..', 'LITNODE', 'litnode'));
  const version = JSON.parse(readFileSync(join(src, 'package.json'), 'utf8')).version;
  mkdirSync(join(out, 'protocol'), { recursive: true });
  const files = {};
  for (const f of FILES) {
    const b = readFileSync(join(src, 'cabinet', f));
    writeFileSync(join(out, f), b.toString('utf8').replace(/\r\n/g, '\n'));
    files[f] = sha(b);
  }
  writeFileSync(join(out, 'MANIFEST.json'), `${JSON.stringify({ note: 'generated by scripts/vendor-litnode.mjs from LitNode (Apache-2.0): do not edit the copies', litnode: version, files }, null, 2)}\n`);
  console.log(`copied ${FILES.length} files from LitNode ${version}`);
}
